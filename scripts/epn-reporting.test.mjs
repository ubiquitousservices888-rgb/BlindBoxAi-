test("blank Custom ID earnings preserve zero-revenue clicks and dated activity", () => {
  const csv = [
    "Status,Custom ID,Partner Network Transaction ID,Day,Clicks,Transactions,Action Earnings,Click Earnings",
    "Confirmed,bb-ch-first,,2026-10-10,2,0,,",
    "Confirmed,bb-ch-second,tx-b,2026-10-10,4,0,$0.75,$0.25",
  ].join("\n");
  const report = parseEpnReportCsv(csv);
  assert.equal(report.networkClicks, 6);
  assert.equal(report.orders, 1);
  assert.equal(report.earnings, 1);
  assert.equal(report.acceptedRows, 1);
  assert.deepEqual(report.daily, [{ date: "2026-10-10", clicks: 4, orders: 0, earnings: 1, epc: 0.25 }]);
});

test("malformed nonblank component values are not silently imported as zero earnings", () => {
  const csv = [
    "Status,Custom ID,Partner Network Transaction ID,Clicks,Transactions,Action Earnings,Click Earnings",
    "Confirmed,bb-ch-bad,,8,0,invalid,",
    "Confirmed,bb-ch-good,,3,0,,",
  ].join("\n");
  const report = parseEpnReportCsv(csv);
  assert.equal(report.networkClicks, 3);
  assert.equal(report.acceptedRows, 0);
  assert.equal(report.earnings, 0);
});


test("mixed EPN report isolates matched, foreign, blank, pending and reversed rows", () => {
  const csv = [
    "Status,Custom ID,Partner Network Transaction ID,Day,Clicks,Transactions,Earnings",
    "Approved,bb-rv-123,tx1,2026-10-20,5,1,$2.50",
    "Confirmed,bb-ch-yt-profile,tx2,2026-10-20,3,1,$1.25",
    "Approved,other-project,tx3,2026-10-20,8,1,$9.00",
    "Approved,,tx4,2026-10-20,2,1,$3.00",
    "Pending,bb-rv-123,tx5,2026-10-20,4,1,$4.00",
    "Reversed,bb-rv-123,tx6,2026-10-20,1,1,-$2.00",
  ].join("\n");
  const report = parseEpnReportCsv(csv);
  assert.equal(report.rowsParsed, 6);
  assert.deepEqual(report.buckets, {
    matched: { rows: 2, clicks: 8, transactions: 2, networkReportedCommissions: 3.75 },
    unmatched_confirmed: { rows: 2, clicks: 10, transactions: 2, networkReportedCommissions: 12 },
    pending: { rows: 1, clicks: 4, transactions: 1, networkReportedCommissions: 4 },
    reversed: { rows: 1, clicks: 1, transactions: 1, networkReportedCommissions: -2 },
  });
  assert.equal(report.earnings, 3.75);
  assert.equal(report.orders, 2);
  assert.equal(report.networkClicks, 8);
  assert.deepEqual(report.matchedCustomIds, ["bb-ch-yt-profile", "bb-rv-123"]);
  assert.equal(report.evidence.length, 2);
});

